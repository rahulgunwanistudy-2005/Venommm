"""Assemble site/ — the static bundle Render serves.

    python experiments/scripts/export_web_bundle.py   # model tables -> web/public/
    python experiments/scripts/build_artifact.py      # tables + template -> one HTML file
    python experiments/scripts/build_site.py          # that file + figures + results -> site/

site/ is committed because Render's static-site build then needs no toolchain at all: the
deploy is a file copy, so it cannot break on a dependency that the model needs but the page
does not. Everything in it is regenerated by the three commands above.
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "web" / "artifact" / "venomgap-atlas.html"
SITE = ROOT / "site"

HEADERS = """/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
/index.html
  Cache-Control: public, max-age=0, must-revalidate
/figures/*
  Cache-Control: public, max-age=86400
/results/*
  Cache-Control: public, max-age=86400
"""


def main() -> None:
    if not PAGE.exists():
        raise SystemExit(
            f"{PAGE} is missing; run export_web_bundle.py then build_artifact.py first"
        )
    if SITE.exists():
        shutil.rmtree(SITE)
    (SITE / "figures").mkdir(parents=True)
    (SITE / "results").mkdir(parents=True)

    shutil.copy(PAGE, SITE / "index.html")
    for path in sorted((ROOT / "figures").glob("*")):
        shutil.copy(path, SITE / "figures" / path.name)
    for path in sorted((ROOT / "results").glob("*.json")):
        shutil.copy(path, SITE / "results" / path.name)
    (SITE / "_headers").write_text(HEADERS)

    total = sum(p.stat().st_size for p in SITE.rglob("*") if p.is_file())
    files = sum(1 for p in SITE.rglob("*") if p.is_file())
    print(f"site/ built: {files} files, {total / 1024 / 1024:.2f} MB")


if __name__ == "__main__":
    main()
